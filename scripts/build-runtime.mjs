import { readFile, writeFile, readdir, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { build } from 'esbuild';
import webpack from 'webpack';
import { runtimeManifest } from './runtime-manifest.mjs';
import { packagePath } from './package-path.mjs';

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const manifest = runtimeManifest(pkg);
for (const [name, version] of Object.entries({ ...pkg.dependencies, ...pkg.devDependencies })) {
  if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(version)) throw new Error(`Dependency must be exactly pinned: ${name}`);
  const installed = JSON.parse(await readFile(resolve(packagePath(name), 'package.json'), 'utf8'));
  if (installed.version !== version) {
    throw new Error(`Dependency version mismatch: ${name}, expected ${version}`);
  }
}
const react = await build({
  stdin: { contents: "import React from 'react'; import * as ReactDOM from 'react-dom'; import {createRoot, hydrateRoot} from 'react-dom/client'; window.React = React; window.ReactDOM = {...ReactDOM, createRoot, hydrateRoot};", resolveDir: resolve(new URL('.', root).pathname) },
  bundle: true, write: false, format: 'iife', platform: 'browser', minify: true,
  define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'inline',
});
const bootstrap = await build({ entryPoints: [new URL('src/frame-runtime.ts', root).pathname], bundle: true, write: false, format: 'iife', platform: 'browser', minify: true, legalComments: 'inline' });
// The published standalone is a webpack-style ESM entry with computed chunk
// imports. A standard context build resolves those imports and merges the
// official chunks without editing any third-party JavaScript source.
const temporary = await mkdtemp(resolve(tmpdir(), 'eficy-runtime-'));
let eficy;
try {
  const compiler = webpack({
    mode: 'production',
    context: resolve(packagePath('@eficy/browser'), 'dist'),
    entry: './standalone.js',
    target: ['web', 'es2022'],
    devtool: false,
    experiments: { outputModule: true },
    module: { parser: { javascript: { importMeta: false } } },
    output: { path: temporary, filename: 'standalone.mjs', module: true, library: { type: 'module' } },
    optimization: { splitChunks: false, runtimeChunk: false },
    plugins: [
      {
        apply(compiler) {
          compiler.hooks.normalModuleFactory.tap('PreserveRuntimeBlobImports', factory => {
            factory.hooks.parser.for('javascript/esm').tap('PreserveRuntimeBlobImports', parser => {
              // loadCode/loadModule import freshly compiled Blob URLs. Keep
              // those native imports; only the relative chunk context is built.
              parser.hooks.importCall.tap('PreserveRuntimeBlobImports', expression => {
                if (expression.source.type === 'Identifier') return true;
              });
            });
          });
        },
      },
      new webpack.ContextReplacementPlugin(/@eficy[/\\]browser[/\\]dist$/, false, /^\.\/\d+\.js$/),
      new webpack.optimize.LimitChunkCountPlugin({ maxChunks: 1 }),
    ],
  });
  const stats = await new Promise((accept, reject) => compiler.run((error, result) => error ? reject(error) : accept(result)));
  await new Promise((accept, reject) => compiler.close(error => error ? reject(error) : accept()));
  if (stats.hasErrors()) throw new Error(stats.toString({ all: false, errors: true }));
  const chunks = [...stats.compilation.chunks];
  if (chunks.length !== 1) throw new Error(`Expected one standalone runtime chunk, got ${chunks.length}`);
  const bundledModules = [...stats.compilation.modules].map(module => module.resource).filter(Boolean);
   const officialChunks = (await readdir(resolve(packagePath('@eficy/browser'), 'dist'))).filter(name => /^\d+\.js$/.test(name));
  for (const name of officialChunks) {
    if (!bundledModules.some(path => path.endsWith(`/${name}`))) throw new Error(`Official runtime chunk was not bundled: ${name}`);
  }
  eficy = await readFile(resolve(temporary, 'standalone.mjs'), 'utf8');
} finally { await rm(temporary, { recursive: true, force: true }); }
const shadcn = await build({
  entryPoints: [new URL('src/shadcn-runtime.ts', root).pathname],
  bundle: true, write: false, format: 'esm', platform: 'browser', minify: true,
  define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'inline',
  external: ['https://*'],
});
const assets = {
  react: react.outputFiles[0].text,
  eficy,
  shadcn: shadcn.outputFiles[0].text,
  shadcnCSS: 'https://cdn.jsdelivr.net/npm/@eficy/shadcn-ui@1.1.3/dist/index.css',
  bootstrap: bootstrap.outputFiles[0].text,
};
await mkdir(new URL('src/generated/', root), { recursive: true });
await writeFile(new URL('src/generated/runtime.ts', root), `// Generated by scripts/build-runtime.mjs; do not edit.\nexport default ${JSON.stringify({ ...assets, manifest })};\n`);
console.log(`Embedded runtime: ${Object.entries(assets).map(([key, text]) => `${key}=${Buffer.byteLength(text)}`).join(', ')} bytes`);
